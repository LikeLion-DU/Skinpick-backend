-- 저장하지 않는 이미지 경로 컬럼 제거 (PRD §9.6)
--
-- 서버는 사진을 받아 Base64 로 OpenAI 에 보내고 버린다. 저장하지 않으므로
-- 채울 값이 없는데 컬럼은 NOT NULL 이라, 그대로 두면 빈 문자열 같은 무의미한
-- 값을 넣게 된다.
--
-- 과거 사진을 다시 꺼내 볼 화면이 없다 — 결과 화면은 앱이 방금 찍은 로컬
-- 파일을 쓰고, 히스토리(S09)는 범위에서 빠졌다. 분석 결과는 DB 에 남으므로
-- 다시 보려면 결과를 보면 되고, 사진이 필요하면 다시 찍으면 된다.
--
-- IF EXISTS 를 쓴 이유: 설계서의 V1 블록은 이미 이 컬럼을 뺀 상태라,
-- 문서를 보고 새로 만든 DB 에는 컬럼이 없다. 그 경우에도 실패하지 않아야 한다.
-- ============================================================

ALTER TABLE skin_analysis DROP COLUMN IF EXISTS image_url;
ALTER TABLE food_analysis DROP COLUMN IF EXISTS image_url;
